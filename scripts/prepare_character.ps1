# Prepare full-body idle, blink, and weight-shift frames from pinned upstream sheets.
param(
    [Parameter(Mandatory = $true)][string]$SourcePath,
    [Parameter(Mandatory = $true)][string]$MotionSourcePath
)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$outputDirectory = Join-Path $PSScriptRoot '../firmware/main/ui/assets'
New-Item -ItemType Directory -Force $outputDirectory | Out-Null

# Trim transparent margins, retain the entire pose, and anchor every frame's feet.
function Export-CharacterFrame {
    param([System.Drawing.Bitmap]$Source, [System.Drawing.Rectangle]$Frame, [string]$Name)
    $left = $Frame.Right; $top = $Frame.Bottom; $right = 0; $bottom = 0
    for ($y = $Frame.Top; $y -lt $Frame.Bottom; $y++) {
        for ($x = $Frame.Left; $x -lt $Frame.Right; $x++) {
            if ($Source.GetPixel($x, $y).A -gt 8) {
                $left = [Math]::Min($left, $x); $right = [Math]::Max($right, $x)
                $top = [Math]::Min($top, $y); $bottom = [Math]::Max($bottom, $y)
            }
        }
    }
    $crop = [System.Drawing.Rectangle]::new($left, $top, $right - $left + 1, $bottom - $top + 1)
    $bitmap = [System.Drawing.Bitmap]::new(80, 84)
    $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
    try {
        $graphics.Clear([System.Drawing.Color]::Transparent)
        $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
        $scale = [Math]::Min(76.0 / $crop.Width, 80.0 / $crop.Height)
        $width = [int][Math]::Round($crop.Width * $scale)
        $height = [int][Math]::Round($crop.Height * $scale)
        $target = [System.Drawing.Rectangle]::new([int]((80 - $width) / 2), 82 - $height, $width, $height)
        $graphics.DrawImage($Source, $target, $crop, [System.Drawing.GraphicsUnit]::Pixel)
        $bitmap.Save((Join-Path $outputDirectory "$Name.png"), [System.Drawing.Imaging.ImageFormat]::Png)
        $lines = [System.Collections.Generic.List[string]]::new()
        $lines.Add('/** Generated by scripts/prepare_character.ps1; see assets/README.md for attribution. */')
        $lines.Add('#include "lvgl.h"')
        $lines.Add('')
        $lines.Add('static const uint8_t pixels[] = {')
        for ($y = 0; $y -lt 84; $y++) {
            $values = [System.Collections.Generic.List[string]]::new()
            for ($x = 0; $x -lt 80; $x++) {
                $color = $bitmap.GetPixel($x, $y)
                foreach ($value in @($color.B, $color.G, $color.R, $color.A)) {
                    $values.Add(('0x{0:x2}' -f $value))
                }
            }
            $lines.Add('  ' + ($values -join ', ') + ',')
        }
        $lines.Add('};')
        $lines.Add('')
        $lines.Add('/** Full-body pose in straight-alpha BGRA, shared by device and desktop. */')
        $lines.Add("const lv_image_dsc_t $Name = {")
        $lines.Add('  .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888,')
        $lines.Add('             .w = 80, .h = 84, .stride = 320},')
        $lines.Add('  .data_size = sizeof(pixels), .data = pixels,')
        $lines.Add('};')
        [System.IO.File]::WriteAllLines((Join-Path $outputDirectory "$Name.c"), $lines)
    } finally {
        $graphics.Dispose()
        $bitmap.Dispose()
    }
}

$idle = [System.Drawing.Bitmap]::new((Resolve-Path -LiteralPath $SourcePath).Path)
$motion = [System.Drawing.Bitmap]::new((Resolve-Path -LiteralPath $MotionSourcePath).Path)
try {
    $frameWidth = [int]($idle.Width / 2)
    Export-CharacterFrame $idle ([System.Drawing.Rectangle]::new(0, 0, $frameWidth, $idle.Height)) 'whale_idle'
    Export-CharacterFrame $idle ([System.Drawing.Rectangle]::new($frameWidth, 0, $frameWidth, $idle.Height)) 'whale_closed'
    $frames = @(1, 3, 5, 7)
    for ($index = 0; $index -lt $frames.Count; $index++) {
        $frame = $frames[$index]
        $tile = [System.Drawing.Rectangle]::new(($frame % 4) * 512, [int][Math]::Floor($frame / 4) * 512, 512, 512)
        Export-CharacterFrame $motion $tile "whale_shift_$index"
    }
} finally {
    $idle.Dispose()
    $motion.Dispose()
}
